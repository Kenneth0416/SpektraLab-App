import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Regenerates android/app/src/main/assets/licenses-data.js from the canonical
// license texts in android/app/src/main/assets/licenses/.
//
// The WebView prototype loads license text from a JS global rather than the
// filesystem, so this file has to stay in sync with the bundled .txt files.
// Generating it removes the drift that previously left the license modal
// rendering an empty body and a stale global name.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = path.join(root, 'android', 'app', 'src', 'main', 'assets');
const licensesDir = path.join(assetsDir, 'licenses');
const outputPath = path.join(assetsDir, 'licenses-data.js');

const docs = [
  { key: 'gpl3', file: 'GPL-3.0.txt' },
  { key: 'ccbysa4', file: 'SPEKTRAFILM_LICENSE.txt' },
  { key: 'changelog', file: 'CHANGELOG.txt' },
  { key: 'notice', file: 'NOTICE.txt' },
];

const texts = {};
for (const doc of docs) {
  texts[doc.key] = await readFile(path.join(licensesDir, doc.file), 'utf8');
}

const banner = `// Generated by scripts/build-licenses-data.mjs — do not edit.
// Source: android/app/src/main/assets/licenses/*.txt
`;
const body = `window.SILVERCAM_LICENSES = ${JSON.stringify(texts)};\n`;
await writeFile(outputPath, banner + body);

console.log(`Wrote ${path.relative(root, outputPath)} (${docs.length} documents)`);
